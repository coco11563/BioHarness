"""Pre-commit + CI guard against non-release content.

The released codebase must read as a normal academic open-source project.
Anything that telegraphs non-release metadata, local tooling names, or
credentials fails CI before reviewers see it.

Usage:
    python scripts/scan_forbidden_strings.py [path ...]

If no path is given, the script scans the working tree minus the standard
ignore set. Exit code 1 on the first hit, with file:line:context.

To override for a single legitimate use, append the marker
``# noqa: framework-eval-forbidden`` on the same line.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Forbidden patterns are case-insensitive substrings (regex).
# Keep the list short; every entry must have a clear "why".
FORBIDDEN: list[tuple[str, str]] = [
    # --- Non-release attribution lines in commit messages or docs.
    (r"co-authored-by:\s*claude", "Non-release attribution in commit metadata."),
    (r"co-authored-by:\s*codex", "Non-release attribution in commit metadata."),
    (r"co-authored-by:\s*gpt", "Non-release attribution in commit metadata."),
    (r"\bgenerated with\s+claude\b", "Non-release attribution string."),
    (r"\bgenerated by\s+claude\b", "Non-release attribution string."),
    (r"\bgenerated with\s+codex\b", "Non-release attribution string."),
    (r"\bgenerated by\s+codex\b", "Non-release attribution string."),
    # --- Local-tooling names that should not appear in shipped artefacts.
    (r"claude code", "Local tooling name in shipped artefacts."),
    (r"\banthropic\b", "Local tooling vendor name in shipped artefacts."),
    (r"oh-my-claudecode", "Local tooling name in shipped artefacts."),
    (r"\bautopilot\s+phase\b", "Local workflow term in shipped artefacts."),
    (r"\bralph\s+state\b", "Local workflow term in shipped artefacts."),
    # --- Credential / token leaks.
    (r"openai .* (api[_-]?key|secret)", "Possible credential leak."),
    (r"openai_api_key\s*=\s*[\"'][^\"']+[\"']", "Possible credential leak."),
    (r"anthropic_api_key\s*=\s*[\"'][^\"']+[\"']", "Possible credential leak."),
    (r"hf_token\s*=\s*[\"'][^\"']+[\"']", "Possible credential leak."),
    (r"sk-[a-z0-9]{20,}", "Possible API key leak."),
    (r"hf_[a-z0-9]{30,}", "Possible Hugging Face token leak."),
    (r"\bbearer\s+[a-z0-9_\-]{20,}", "Possible bearer-token leak."),
]

IGNORE_DIRS = {
    ".git", ".venv", "venv", "env", "__pycache__", ".pytest_cache",
    ".mypy_cache", ".ruff_cache", "node_modules", "dist", "build",
    ".cache", "data", "output",
}
# Files always scanned regardless of suffix.
ALWAYS_SCAN_NAMES = {
    "LICENSE", "NOTICE", "Dockerfile", "Makefile",
    ".gitignore", ".python-version", ".pre-commit-config.yaml",
}
TEXT_SUFFIXES = {
    ".py", ".md", ".toml", ".yaml", ".yml", ".cff", ".cfg", ".ini",
    ".txt", ".sh", ".rst", ".json", ".tsv", ".csv",
}
NOQA_MARKER = "# noqa: framework-eval-forbidden"

PATTERNS = [(re.compile(p, re.IGNORECASE), why) for p, why in FORBIDDEN]


def iter_files(roots: list[Path]) -> list[Path]:
    out: list[Path] = []
    for root in roots:
        if root.is_file():
            out.append(root)
            continue
        for p in root.rglob("*"):
            if not p.is_file():
                continue
            if any(part in IGNORE_DIRS for part in p.parts):
                continue
            if p.suffix in TEXT_SUFFIXES or p.name in ALWAYS_SCAN_NAMES:
                out.append(p)
    return out


_SCANNER_PATH = Path(__file__).resolve()


def scan_file(path: Path) -> list[tuple[int, str, str]]:
    # Skip the scanner itself: the pattern table is by definition a hit.
    if path.resolve() == _SCANNER_PATH:
        return []
    hits: list[tuple[int, str, str]] = []
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return hits
    for lineno, line in enumerate(text.splitlines(), 1):
        if NOQA_MARKER in line:
            continue
        for pattern, why in PATTERNS:
            if pattern.search(line):
                hits.append((lineno, line.rstrip(), why))
                break
    return hits


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("paths", nargs="*", default=["."], help="files or directories to scan")
    args = ap.parse_args(argv)

    roots = [Path(p).resolve() for p in args.paths]
    failures = 0
    for f in iter_files(roots):
        for lineno, line, why in scan_file(f):
            print(f"{f}:{lineno}: {why}\n  {line}")
            failures += 1

    if failures:
        print(f"\nforbidden-string scan: {failures} hit(s)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
